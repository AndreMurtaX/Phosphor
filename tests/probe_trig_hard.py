"""Writes tests/probe_trig_hard.inc: per binade, the two Doubles closest to a
multiple of pi/2 -- the arguments whose reduction loses the most bits.

    python tests/probe_trig_hard.py > tests/probe_trig_hard.inc

A Double x = m * 2^e (m a 53-bit integer) is close to a multiple of pi/2 when
m * beta is close to an integer, beta = frac(2^e * 2/pi). The m that make it
closest come from the continued fraction of beta: its convergent denominators
q, and small combinations j*q + k*q' of consecutive ones, inside [2^52, 2^53).
pi comes from Machin's formula in integers, 1600 bits, so nothing here is a
floating-point library's answer. For e = 797 it finds 6381956970095103, the
hardest Double to reduce (Muller, Elementary Functions, ch. 11), and says so.
"""
import struct
import sys
from fractions import Fraction


def arctan_inv(x, prec):
    """arctan(1/x) * 2^prec, as an integer."""
    total = term = (1 << prec) // x
    x2, n, sign = x * x, 1, -1
    while term:
        term //= x2
        total += sign * (term // (2 * n + 1))
        sign, n = -sign, n + 1
    return total


PREC = 1600
PI_FIX = 4 * (4 * arctan_inv(5, PREC + 30) - arctan_inv(239, PREC + 30))
TWO_OVER_PI = (1 << (2 * PREC + 31)) // PI_FIX     # 2/pi * 2^PREC
A, B = 1 << 52, 1 << 53


def dist(m, num, den):
    v = m * num % den
    return min(v, den - v)


def denominators(num, den):
    out, q2, q1 = [], 1, 0
    while den and q1 < B:
        a = num // den
        q2, q1 = q1, a * q1 + q2
        out.append(q1)
        num, den = den, num - a * den
    return [q for q in out if 0 < q < B]


def hardest(e):
    den = 1 << PREC
    if e >= 0:
        num = (TWO_OVER_PI << e) % den
    else:
        den <<= -e
        num = TWO_OVER_PI % den
    qs = denominators(num, den)
    cand = set()
    for i, q in enumerate(qs):
        if q < (1 << 24):
            continue
        qp = qs[i - 1] if i > 0 else 1
        for j in range(1, 17):
            for k in range(-16, 17):
                if A <= j * q + k * qp < B:
                    cand.add(j * q + k * qp)
        lo = -(-A // q)
        for j in range(lo, lo + 8):
            if A <= j * q < B:
                cand.add(j * q)
    return sorted(cand, key=lambda m: dist(m, num, den))[:2]


def bits(m, e):
    v = Fraction(m) * Fraction(2) ** e
    x = float(v)
    assert Fraction(x) == v
    return struct.unpack('<Q', struct.pack('<d', x))[0]


def main():
    vals, found = [], False
    for e in range(-53, 972):               # x from 2^-1 to 2^1024
        for m in hardest(e):
            vals.append(bits(m, e))
            found = found or (e == 797 and m == 6381956970095103)
    if not found:
        sys.exit('6381956970095103 * 2^797 was not found: the search is wrong')
    sys.stdout.reconfigure(newline='\n')    # the tree is LF (.gitattributes)
    print('{ Generated by tests/probe_trig_hard.py -- do not edit. }')
    print('const')
    print('  HARD_N = %d;' % len(vals))
    print('  HARD: array[0..HARD_N - 1] of QWord = (')
    rows = ['    ' + ', '.join('$%016X' % b for b in vals[i:i + 4])
            for i in range(0, len(vals), 4)]
    print(',\n'.join(rows) + ');')


if __name__ == '__main__':
    main()
